# Trees missing from the model, read off the Google z20 ortho per zone (R1 greybox). Crowns = the dark canopy/shadow
# masses in the zone polygon, split into single crowns by distance-transform peaks (trunk ~ mass centre: the crown leans
# east/north with height on this ortho while its morning shadow falls west/north-west). Trunks are kept off the zone's
# paths/hedges/structures, crowns are narrowed so they do not pierce roofs, and crowns already modelled by any spec are
# skipped. One generated spec per zone (tree elements only).
# Run: uv run --project Scripts python Scripts/Geo/ortho_trees.py [--zone NAME] [--debug DIR]
import argparse
import glob
import json
import math
import os

import cv2
import numpy as np
import rasterio.features
from affine import Affine
from shapely.geometry import LineString, Point, Polygon
from shapely.ops import unary_union

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SPECS = os.path.join(REPO, "Art", "Blender", "Specs")
ORTHO = os.path.expanduser("~/site-capture/ortho/ortho_google_z20")
RES = 0.1                                  # native ortho resolution, m/px
CLEAR = 0.9                                # m: trunk clearance from path/hedge/wall centre lines
EV = ("crown on the Google z20 ortho 2026 (dark canopy/shadow mass, r %.1f m); species class by crown size; "
      "generated by Scripts/Geo/ortho_trees.py")
# zone: polygon, output spec, collection, blurred-darkness threshold, min crown radius / separation (m), the spec whose
# path/hedge/wall/gazebo/pergola elements keep trunks and crowns clear, and what the zone looks like on the footage
ZONES = {
    "garden": dict(out="SITE_Garden_Trees", collection="04_Garden", dark=72.0, min_r=1.1, min_sep=3.2, clear_spec="SITE_Garden",
                   # inside the measured 7-sided boundary hedge (zone_garden.py v2 outline, 0.7 m in)
                   poly=[(99.5, -36.9), (103.5, -44.3), (150.2, -45.95), (153.0, -44.0), (156.2, -38.8), (157.55, -14.4),
                         (101.2, -10.5)],
                   note="formal garden: thujas, pines, acacias, poplars (garden videos 081856-082013)"),
    "west_strip": dict(out="SITE_Trees_WestStrip", collection="06_Vegetation", dark=85.0, min_r=0.7, min_sep=2.4,
                       clear_spec=None, poly=[(79.2, 25.0), (89.0, 24.6), (90.2, 78.5), (80.4, 79.0)],
                       note="lawn strip W of the football pitch with rows of clipped shrubs and small trees (ortho; pano "
                            "c_intro1 2022: conifers and roses in lawn beds)"),
    "east_belt": dict(out="SITE_Trees_EastBelt", collection="06_Vegetation", dark=80.0, min_r=1.3, min_sep=3.5, clear_spec=None,
                      poly=[(210.5, -100.0), (224.0, -100.0), (224.0, 92.0), (215.5, 92.0)],
                      note="tall tree belt along the E fence / service road (ortho; pano c_intro_2 2022: poplars beyond the "
                           "courts)"),
}


def existing_trees(exclude_out):
    pts = []
    for fn in glob.glob(os.path.join(SPECS, "SITE_*.json")):
        if os.path.basename(fn)[:-5] == exclude_out:
            continue
        for e in json.load(open(fn)).get("elements", []):
            if e.get("type") == "tree" and isinstance(e.get("pos"), list) and len(e["pos"]) == 2:
                pts.append((e["pos"][0], e["pos"][1], e.get("crown_d", 3.0)))
    return pts


def run_zone(name, z, img_full, meta, debug_dir):
    X0, Y0, X1, Y1 = meta["extent_local"]
    poly = Polygon(z["poly"])
    gx0, gy0, gx1, gy1 = poly.buffer(5).bounds
    c0, r0 = int((gx0 - X0) / RES), int((Y1 - gy1) / RES)
    c1, r1 = int((gx1 - X0) / RES), int((Y1 - gy0) / RES)
    img = img_full[r0:r1, c0:c1, ::-1].astype(np.float32)
    H, W = img.shape[:2]
    T = Affine(RES, 0, c0 * RES + X0, 0, -RES, Y1 - r0 * RES)
    V = img.max(axis=2)
    canopy = (cv2.GaussianBlur(V, (0, 0), 3) < z["dark"]).astype(np.uint8)
    canopy = cv2.morphologyEx(canopy, cv2.MORPH_OPEN, np.ones((9, 9), np.uint8))
    canopy = cv2.morphologyEx(canopy, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
    canopy &= rasterio.features.rasterize([(poly, 1)], out_shape=(H, W), transform=T, dtype=np.uint8)
    dist = cv2.distanceTransform(canopy, cv2.DIST_L2, 5) * RES           # m to the crown edge
    k = int(z["min_sep"] / RES) | 1
    peaks = (dist == cv2.dilate(dist, np.ones((k, k), np.float32))) & (dist >= z["min_r"])
    ys, xs = np.nonzero(peaks)
    order = np.argsort(-dist[ys, xs])
    lines, blocks, roofs = [], [], []   # roofs: structures a crown must not grow through
    if z["clear_spec"]:
        for e in json.load(open(os.path.join(SPECS, z["clear_spec"] + ".json")))["elements"]:
            if e["type"] in ("path", "hedge", "wall") and e.get("line"):
                lines.append(LineString(e["line"]).buffer(CLEAR + e.get("width", 0.3) / 2))
            elif e["type"] == "gazebo":
                blocks.append(Point(e["center"]).buffer(e.get("across_flats", 7.7) / 2 + 1.0))
                roofs.append(Point(e["center"]).buffer(e.get("across_flats", 7.7) / 2 + e.get("overhang", 0.8)))
            elif e["type"] == "pergola":
                blocks.append(LineString(e["line"]).buffer(e.get("width", 2.0) / 2 + 0.6))
                roofs.append(LineString(e["line"]).buffer(e.get("width", 2.0) / 2 + 0.2))
    lawn = poly.buffer(-0.8).difference(unary_union(lines + blocks)) if lines or blocks else poly.buffer(-0.8)
    old = existing_trees(z["out"])
    trees = []
    for i in order:
        r = float(dist[ys[i], xs[i]])
        tx, ty = T * (xs[i] + 0.5, ys[i] + 0.5)
        d = min(10.0, 2.0 * r)                           # crown diameter (crown + shadow mass: an upper bound)
        p = Point(tx, ty)
        if not lawn.contains(p):
            q = lawn.boundary.interpolate(lawn.boundary.project(p)) if not lawn.is_empty else None
            if q is None or q.distance(p) > 1.5:
                continue
            tx, ty = q.x, q.y
        if any(math.hypot(tx - t["pos"][0], ty - t["pos"][1]) < z["min_sep"] for t in trees):
            continue
        if any(math.hypot(tx - ox, ty - oy) < max(1.5, (od + d) / 4) for ox, oy, od in old):
            continue                                     # already modelled by a hand-placed tree
        room = min((rf.distance(Point(tx, ty)) for rf in roofs), default=99.0)
        if d / 2 > room:          # crown would pierce a gazebo/pergola roof: narrower crown (min 2 m) or no tree
            if room < 1.0:
                continue
            d = 2.0 * room
        conifer = d < 3.4
        h = (1.8 * d + 1.0) if conifer else min(18.0, 1.2 * d + 5.0)
        trees.append({"type": "tree", "name": f"OT_{name}_{len(trees):02d}_{'conifer' if conifer else 'broadleaf'}",
                      "pos": [round(tx, 2), round(ty, 2)], "height": round(h, 1), "crown_d": round(d, 1),
                      "trunk_d": 0.18 if conifer else 0.3, "crown_base": round(0.15 * h if conifer else 0.35 * h, 1),
                      "shape": "cone" if conifer else "round", "ue_asset": "tree", "evidence": EV % r, "confidence": "low"})
    spec = {"id": z["out"], "collection": z["collection"], "ground": "terrain",
            "note": f"Trees read off the ortho for zone '{name}' ({z['note']}); none of them was modelled before. Generated "
                    "by Scripts/Geo/ortho_trees.py; regenerate after moving paths/hedges/trees nearby.",
            "elements": trees}
    json.dump(spec, open(os.path.join(SPECS, z["out"] + ".json"), "w"), indent=1)
    print(f"{name}: {len(trees)} trees ({sum(t['shape'] == 'cone' for t in trees)} conifers) -> {z['out']}.json")
    if debug_dir:
        dbg = img.copy()
        dbg[canopy > 0] = dbg[canopy > 0] * 0.5 + np.array([255, 255, 0]) * 0.5
        inv = ~T
        for t in trees:
            px, py = inv * tuple(t["pos"])
            cv2.circle(dbg, (int(px), int(py)), int(t["crown_d"] / 2 / RES), (255, 0, 0), 2)
        cv2.imwrite(os.path.join(debug_dir, f"trees_{name}.png"), dbg[:, :, ::-1].astype(np.uint8))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zone", choices=sorted(ZONES))
    ap.add_argument("--debug")
    args = ap.parse_args()
    meta = json.load(open(ORTHO + ".json"))
    img = cv2.imread(ORTHO + ".png")
    for name, z in ZONES.items():
        if args.zone in (None, name):
            run_zone(name, z, img, meta, args.debug)


if __name__ == "__main__":
    main()
